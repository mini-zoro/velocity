"""Generate the compact Emoji_Presentation table from Unicode's emoji-data.txt.

Input: https://www.unicode.org/Public/18.0.0/ucd/emoji/emoji-data.txt
Usage (from the repository root): python3 crates/vel-render/fixtures/generate_emoji_presentation.py INPUT
"""
import hashlib
from pathlib import Path
import sys

source = Path(sys.argv[1]).read_bytes()
digest = hashlib.sha256(source).hexdigest()
if digest != "80d00f8e616a0ef27fd6b8de3b758c06383b5d917e2977709578e68baf733bf1":
    raise SystemExit("Expected the cited Unicode 18.0.0 data; update the version and digest together.")
ranges = []
for line in source.decode().splitlines():
    fields = line.split("#", 1)[0].strip().split(";")
    if len(fields) != 2 or fields[1].strip() != "Emoji_Presentation":
        continue
    bounds = fields[0].strip().split("..")
    lo, hi = int(bounds[0], 16), int(bounds[-1], 16)
    if ranges and lo == ranges[-1][1] + 1:
        ranges[-1] = (ranges[-1][0], hi)
    else:
        ranges.append((lo, hi))

target = Path(__file__).resolve().parent.parent / "src/emoji_presentation.rs"
text = """// Generated by fixtures/generate_emoji_presentation.py; do not edit the ranges.
// Unicode 18.0.0 Emoji_Presentation=Yes:
// https://www.unicode.org/Public/18.0.0/ucd/emoji/emoji-data.txt
// Copyright © 2026 Unicode, Inc. Unicode License v3 (fixtures/UNICODE-LICENSE.txt).
"""
text += f"// Input SHA-256: {digest}\n"
text += """
pub(super) fn default_presentation(c: char) -> bool {
    let c = c as u32;
    RANGES
        .binary_search_by(|&(lo, hi)| {
            if c < lo {
                std::cmp::Ordering::Greater
            } else if c > hi {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

const RANGES: &[(u32, u32)] = &[
"""
text += "".join(f"    (0x{lo:x}, 0x{hi:x}),\n" for lo, hi in ranges)
text += "];\n"
temp = target.with_suffix(".tmp")
temp.write_text(text)
temp.replace(target)
print(f"{len(ranges)} ranges, {sum(hi - lo + 1 for lo, hi in ranges)} scalars")
