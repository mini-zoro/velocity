#[derive(Clone)]
struct CommentMarker {
    number: u64,
    start: String,
    end: String,
    column_zero: bool,
    insensitive: bool,
}
impl CommentMarker {
    fn starts(&self, text: &str, marker: &str) -> bool {
        if self.insensitive {
            text.get(..marker.len())
                .is_some_and(|head| head.eq_ignore_ascii_case(marker))
        } else {
            text.starts_with(marker)
        }
    }
    fn ends(&self, text: &str, marker: &str) -> bool {
        text.len()
            .checked_sub(marker.len())
            .and_then(|i| text.get(i..))
            .is_some_and(|tail| self.starts(tail, marker))
    }
    fn line_marker_len(&self, line: &str) -> Option<usize> {
        let marker = self.start.trim_end();
        let word = |c: char| c == '_' || c.is_alphanumeric();
        if marker.is_empty()
            || !self.starts(line, marker)
            || marker.ends_with(word) && line[marker.len()..].starts_with(word)
        {
            return None;
        }
        Some(if self.starts(line, &self.start) {
            self.start.len()
        } else {
            marker.len()
        })
    }
    fn enclosing_lengths(&self, source: &str, padded: bool) -> Option<(usize, usize)> {
        let left = self.start.trim_end();
        let right = self.end.trim_start();
        if !self.starts(source, left) || !self.ends(source, right) {
            return None;
        }
        let mut a = if self.starts(source, &self.start) {
            self.start.len()
        } else {
            left.len()
        };
        let mut b = if self.ends(source, &self.end) {
            self.end.len()
        } else {
            right.len()
        };
        // The block-only whole-line command inserts one space on either side.
        if padded && source.len() >= a + b + 2 {
            a += usize::from(a == left.len() && source.as_bytes().get(a) == Some(&b' '));
            b += usize::from(
                b == right.len() && source.as_bytes().get(source.len() - b - 1) == Some(&b' '),
            );
        }
        (a + b <= source.len()).then_some((a, b))
    }
}

fn scope_prefix(name: &str, scope: vel_scope::Scope) -> bool {
    // Scope construction interns nothing after the first use; compare atoms without strings.
    vel_scope::Scope::new(name).is_ok_and(|prefix| prefix.is_prefix_of(scope))
}
fn tag_selector() -> &'static vel_scope::Selector {
    static SELECTOR: std::sync::OnceLock<vel_scope::Selector> = std::sync::OnceLock::new();
    SELECTOR.get_or_init(|| {
        vel_scope::Selector::parse(
            "text.html - comment - string - markup.raw, text.xml - comment - string - markup.raw",
        )
        .expect("markup selector")
    })
}
fn tag_scopes(scopes: &[vel_scope::Scope]) -> bool {
    let markup = scopes
        .iter()
        .rposition(|s| scope_prefix("text.html", *s) || scope_prefix("text.xml", *s));
    let source = scopes.iter().rposition(|s| scope_prefix("source", *s));
    tag_selector().matches(scopes)
        && markup.is_some_and(|markup| source.is_none_or(|source| source < markup))
}
fn html_void_tag(name: &str) -> bool {
    [
        "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param",
        "source", "track", "wbr",
    ]
    .iter()
    .any(|tag| name.eq_ignore_ascii_case(tag))
}
