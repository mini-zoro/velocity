/// Provenance for whitespace generated by the last automatic newline or its typed prefix.
#[derive(Debug)]
pub(crate) struct AutomaticIndents {
    buffer: vel_buffer::BufferId,
    version: vel_buffer::ChangeId,
    settings: u64,
    lines: Vec<Option<IndentedCaret>>,
    groups: Vec<IndentGroup>,
    scratch: String,
    steps: Vec<IndentStep>,
}

#[derive(Debug, Clone, Copy)]
struct IndentedCaret {
    next: usize,
    group: usize,
}

#[derive(Debug, Clone)]
struct IndentSeed {
    original: String,
    reduced: String,
    suffix: String,
    rule: IndentRule,
}

#[derive(Debug, Clone)]
struct IndentGroup {
    seed: IndentSeed,
    typed: String,
    dedented: bool,
}

#[derive(Debug)]
enum IndentStep {
    Stop,
    Unchanged,
    Adjust { remove: usize, text: String },
}

impl IndentGroup {
    fn advance(&mut self, value: &str, candidate: &mut String) -> IndentStep {
        let IndentSeed {
            original,
            reduced,
            suffix,
            rule,
        } = &self.seed;
        if value.is_empty()
            || value.contains('\n')
            || original.len() + self.typed.len() + value.len() + suffix.len() > DEDENT_LIMIT
            || self.typed.is_empty() && value.starts_with([' ', '\t'])
        {
            return IndentStep::Stop;
        }
        // Use the original indentation even if an earlier keyword prefix matched.
        // Spaces after code are not manual indentation (e.g. Python's `except E:`).
        // https://docs.sublimetext.io/reference/metadata.html#indentation-options
        candidate.clear();
        candidate.push_str(original);
        candidate.push_str(&self.typed);
        candidate.push_str(value);
        candidate.push_str(suffix);
        let decrease = rule.is_match(candidate);
        let old_prefix = self.typed.len();
        self.typed.push_str(value);
        if decrease == self.dedented {
            return IndentStep::Unchanged;
        }
        let (old, new) = if decrease {
            (original, reduced)
        } else {
            (reduced, original)
        };
        self.dedented = decrease;
        let mut text = String::with_capacity(new.len() + self.typed.len());
        text.push_str(new);
        text.push_str(&self.typed);
        IndentStep::Adjust {
            remove: old.len() + old_prefix,
            text,
        }
    }
}

#[derive(Clone, Copy)]
enum TypedInsert<'a> {
    Uniform(&'a str),
    PerCaret(&'a [(String, Range<usize>)]),
}
impl<'a> TypedInsert<'a> {
    fn at(self, i: usize) -> (&'a str, Range<usize>) {
        match self {
            Self::Uniform(s) => (s, s.len()..s.len()),
            Self::PerCaret(v) => (v[i].0.as_str(), v[i].1.clone()),
        }
    }
}

type IndentRule = vel_syntax::metadata::MetadataPattern;
const DEDENT_LIMIT: usize = 256;
const EXACT_SCOPE_BYTES: usize = 256 * 1024;
const EXACT_SCOPE_LINES: usize = 256;
type IndentedNewline = (String, Range<usize>, Option<Range<usize>>, Option<usize>);

struct NewlineRules {
    excluded: Option<IndentRule>,
    disabled: Option<IndentRule>,
    increase: Option<IndentRule>,
    bracket: Option<IndentRule>,
    decrease: Option<IndentRule>,
    code: bool,
}
impl NewlineRules {
    fn new(language: &crate::language::Language, scopes: &vel_scope::ScopeStack) -> Self {
        let metadata = &language.assets.metadata;
        let selected = metadata.metadata_for(scopes);
        let pattern = |key| metadata.pattern(&selected, key);
        let string = scope_named("string");
        let comment = scope_named("comment");
        Self {
            excluded: pattern("unIndentedLinePattern"),
            disabled: pattern("disableIndentNextLinePattern"),
            increase: pattern("increaseIndentPattern"),
            bracket: pattern("bracketIndentNextLinePattern"),
            decrease: pattern("decreaseIndentPattern").filter(|re| re.compile_error().is_none()),
            code: !scopes
                .as_slice()
                .iter()
                .any(|&s| string.is_prefix_of(s) || comment.is_prefix_of(s)),
        }
    }
}

fn scope_named(name: &'static str) -> vel_scope::Scope {
    vel_scope::Scope::new(name).expect("built-in scope")
}

impl Editor {
    /// Exact scopes for a command; stale publications never authorize an edit.
    pub(crate) fn exact_scopes(&self, points: &[usize]) -> Option<Vec<Vec<vel_scope::Scope>>> {
        let language = self.language.borrow();
        let language = language.as_ref()?;
        // Commands can query after the buffer commit but before the view sync.
        let text = self.buffer.text();
        if text.is_empty() {
            return Some(vec![vec![language.root]; points.len()]);
        }
        if points.iter().all(|&p| language.scopes_ready_at(text, p)) {
            return Some(
                points
                    .iter()
                    .map(|&p| language.scopes(text, p).as_slice().to_vec())
                    .collect(),
            );
        }
        let point = *points.iter().max()?;
        let row = text.byte_to_line(point.min(text.len_bytes()));
        let cache = self.exact_scope_prefix(language, row)?;
        points
            .iter()
            .map(|&p| {
                let at = p.min(text.len_bytes());
                cache
                    .spans
                    .get(cache.spans.partition_point(|s| s.range.end <= at))
                    .filter(|s| s.range.contains(&at))
                    .map(|s| s.scopes.clone())
            })
            .collect()
    }

    fn last_bounded_scope_row(&self) -> Option<usize> {
        let text = self.buffer.text();
        let rows = if text.len_bytes() <= EXACT_SCOPE_BYTES {
            text.len_lines()
        } else {
            text.byte_to_line(text.floor_char_boundary(EXACT_SCOPE_BYTES))
        };
        rows.min(EXACT_SCOPE_LINES).checked_sub(1)
    }

    fn exact_scope_prefix(
        &self,
        language: &crate::language::Language,
        row: usize,
    ) -> Option<Ref<'_, ExactScopeCache>> {
        let text = self.buffer.text();
        let end = if row + 1 < text.len_lines() {
            text.line_to_byte(row + 1)
        } else {
            text.len_bytes()
        };
        // Editing and pointer-hover fallback only. Other display queries use published
        // scopes; hover suppresses its popup when this exact prefix exceeds the budget.
        // Bound both allocation and parser work, including a long line earlier in the prefix.
        if end > EXACT_SCOPE_BYTES
            || row >= EXACT_SCOPE_LINES
            || self.features.highlighting == vel_largefile::HighlightMode::Viewport
            || self.document_metrics.longest_line_bytes > 8192
        {
            return None;
        }
        let buffer = self.buffer.id();
        let version = self.buffer.change_id();
        let assets = std::sync::Arc::as_ptr(&language.assets) as usize;
        {
            let cache = self.exact_scope_cache.borrow();
            if cache.through >= end
                && cache.identity.as_ref().is_some_and(|(b, v, syntax, a)| {
                    (*b, *v, syntax.as_str(), *a)
                        == (buffer, version, language.syntax.as_str(), assets)
                })
            {
                return Some(cache);
            }
        }
        if (0..=row).any(|line| text.line_len_bytes(line) > 8192) {
            return None;
        }
        let syntax = language
            .assets
            .syntaxes
            .find_syntax_by_path(&language.syntax)?;
        // Parse only through the caret line. An extra LF gives EOF/empty-line carets
        // their own scopes, rather than borrowing the preceding comment's scopes.
        let mut prefix = text.slice(0..end).to_string();
        if end == text.len_bytes() {
            prefix.push('\n');
        }
        #[cfg(test)]
        self.exact_scope_parses
            .set(self.exact_scope_parses.get() + 1);
        let mut cache = self.exact_scope_cache.borrow_mut();
        cache.spans =
            vel_syntax::indent::scoped_spans(&language.assets.syntaxes, syntax, &prefix).ok()?;
        cache.identity = Some((buffer, version, language.syntax.clone(), assets));
        cache.through = end;
        drop(cache);
        Some(self.exact_scope_cache.borrow())
    }
    /// Typing hooks may use ready scopes or a bounded exact prefix, never a guessed state.
    fn bounded_scopes(&self, points: &[usize]) -> Option<Vec<Vec<vel_scope::Scope>>> {
        let end = *points.iter().max()?;
        let ready = self
            .language
            .borrow()
            .as_ref()
            .is_some_and(|l| points.iter().all(|&p| l.scopes_ready_at(&self.text, p)));
        let row = self.text.byte_to_line(end);
        let line_end = if row + 1 < self.text.len_lines() {
            self.text.line_to_byte(row + 1)
        } else {
            self.text.len_bytes()
        };
        if !ready && (line_end > 64 * 1024 || row > 256) {
            return None;
        }
        self.exact_scopes(points)
    }

    fn block_comment_regions(
        &self,
        l: &crate::language::Language,
        point: usize,
    ) -> Vec<Range<usize>> {
        if l.scopes_ready_at(&self.text, point) {
            return crate::language::command_scope_regions(l, point, "comment.block");
        }
        let prefix = scope_named("comment.block");
        let regions = |row| {
            let cache = self.exact_scope_prefix(l, row)?;
            let i = cache.spans.partition_point(|s| s.range.end <= point);
            let active = cache
                .spans
                .get(i)
                .filter(|span| span.range.contains(&point))?;
            let mut complete = Vec::new();
            let mut truncated = false;
            for scope in active.scopes.iter().filter(|&&s| prefix.is_prefix_of(s)) {
                let inside = |s: &&vel_syntax::ScopedSpan| s.scopes.contains(scope);
                let a = cache.spans[..i]
                    .iter()
                    .rev()
                    .take_while(inside)
                    .last()
                    .unwrap_or(active);
                let b = cache.spans[i + 1..]
                    .iter()
                    .take_while(inside)
                    .last()
                    .unwrap_or(active);
                if b.range.end == cache.through && cache.through < self.text.len_bytes() {
                    truncated = true;
                } else {
                    complete.push(a.range.start..b.range.end.min(self.text.len_bytes()));
                }
            }
            Some((complete, truncated))
        };
        let row = self.text.byte_to_line(point);
        let Some((complete, truncated)) = regions(row) else {
            return Vec::new();
        };
        if truncated && let Some(last) = self.last_bounded_scope_row().filter(|&last| last > row) {
            return regions(last).map_or(complete, |(complete, _)| complete);
        }
        complete
    }

    fn enclosing_block_comment(
        &self,
        language: &crate::language::Language,
        region: Region,
    ) -> Option<Range<usize>> {
        let ranges = |point| self.block_comment_regions(language, point).into_iter();
        if let Some(comment) = ranges(region.begin())
            .filter(|c| region.end() <= c.end)
            .max_by_key(|c| c.start)
        {
            return Some(comment);
        }
        // A whole-line wrap can leave the caret immediately after the closing
        // marker. Look at the adjacent character's exact scope, not its text.
        if region.empty() && region.b > 0 {
            let row = self.text.byte_to_line(region.b);
            if region.b == self.text.line_to_byte(row) + self.text.line_len_bytes(row) {
                let left = self.text.floor_char_boundary(region.b - 1);
                return ranges(left)
                    .filter(|c| c.end == region.b)
                    .max_by_key(|c| c.start);
            }
        }
        None
    }
    pub fn apply_edits(
        &mut self,
        mut owned: Vec<(Range<usize>, String)>,
        after: Option<Selection>,
        kind: EditKind,
    ) {
        if self.read_only || owned.is_empty() {
            return;
        }
        owned.sort_by_key(|(r, _)| (r.start, r.end));
        owned.dedup_by(|a, b| a.0 == b.0);
        if let Some(mut fields) = self.fields.take() {
            let input: Vec<_> = owned
                .iter()
                .map(|(range, text)| vel_snippet::SnippetEdit {
                    range: range.clone(),
                    text: text.clone(),
                })
                .collect();
            let old_fields = fields.selections();
            let input_changes = ChangeSet::new(
                input
                    .iter()
                    .map(|e| Change {
                        old_range: e.range.clone(),
                        new_len: e.text.len(),
                    })
                    .collect(),
            );
            match fields.edit_fields(self.buffer.text(), &input) {
                Ok(edits) => {
                    let new_fields = fields.selections();
                    let requested = after.as_ref();
                    let selection = Selection::from_regions(
                        self.buffer
                            .view(self.id)
                            .sel()
                            .iter()
                            .enumerate()
                            .filter_map(|(selection_index, r)| {
                                let i = old_fields
                                    .iter()
                                    .position(|f| f.start <= r.begin() && r.end() <= f.end)?;
                                let start =
                                    input_changes.transform_point(old_fields[i].start, Bias::Left);
                                let desired = requested
                                    .and_then(|selection| selection.iter().nth(selection_index))
                                    .unwrap_or_else(|| {
                                        Region::caret(
                                            input_changes.transform_point(r.end(), Bias::Right),
                                        )
                                    });
                                let map = |point: usize| {
                                    (new_fields[i].start + point.saturating_sub(start))
                                        .min(new_fields[i].end)
                                };
                                Some(Region::new(map(desired.a), map(desired.b)))
                            }),
                    );
                    let edits: Vec<_> = edits
                        .iter()
                        .map(|e| Edit {
                            range: e.range.clone(),
                            text: &e.text,
                        })
                        .filter(|e| !self.buffer.edit_is_noop(e))
                        .collect();
                    let caret_edits: Vec<_> = input
                        .iter()
                        .map(|e| Edit {
                            range: e.range.clone(),
                            text: &e.text,
                        })
                        .collect();
                    self.fields = Some(fields);
                    // https://www.sublimetext.com/docs/completions.html (mirrored snippet fields).
                    // Group by the typed characters, not by the rendered mirrors.
                    self.transact_direct_impl(&edits, selection, kind, Some(&caret_edits));
                    return;
                }
                Err(_) => {
                    if fields.rebase(&input_changes) {
                        self.fields = Some(fields);
                    }
                }
            }
        }
        // Selection effects belong to the requested command, including replacements whose
        // bytes already match. Only text publication uses the filtered change set.
        let selection = after.unwrap_or_else(|| {
            let changes = ChangeSet::new(
                owned
                    .iter()
                    .map(|(r, s)| Change {
                        old_range: r.clone(),
                        new_len: s.len(),
                    })
                    .collect(),
            );
            let old = self.buffer.view(self.id).sel();
            selection_primary(
                old.iter()
                    .map(|r| {
                        Region::new(
                            changes.transform_point(r.a, Bias::Right),
                            changes.transform_point(r.b, Bias::Right),
                        )
                    })
                    .collect(),
                old.primary_index(),
            )
        });
        owned.retain(|(range, text)| {
            !self.buffer.edit_is_noop(&Edit {
                range: range.clone(),
                text,
            })
        });
        let edits: Vec<_> = owned
            .iter()
            .map(|(range, text)| Edit {
                range: range.clone(),
                text,
            })
            .collect();
        self.transact_direct(&edits, selection, kind);
    }
    fn transact_direct(&mut self, edits: &[Edit<'_>], selection: Selection, kind: EditKind) {
        self.transact_direct_impl(edits, selection, kind, None);
    }
    fn transact_direct_impl(
        &mut self,
        edits: &[Edit<'_>],
        selection: Selection,
        kind: EditKind,
        caret_edits: Option<&[Edit<'_>]>,
    ) {
        if edits.is_empty() {
            if self.buffer.view(self.id).sel() != &selection {
                self.buffer.set_selection(self.id, selection);
            }
            return;
        }
        let changes = ChangeSet::new(
            edits
                .iter()
                .map(|edit| Change {
                    old_range: edit.range.clone(),
                    new_len: edit.text.len(),
                })
                .collect(),
        );
        let old = self.buffer.text().clone();
        let before_version = self.buffer.change_id();
        self.layout
            .borrow_mut()
            .prepare_change((self.buffer.id(), self.buffer.change_id()));
        if let Some(caret_edits) = caret_edits {
            self.buffer
                .transact_projected(self.id, kind, edits, selection, caret_edits);
        } else {
            self.buffer.transact(self.id, kind, edits, selection);
        }
        self.publish_direct_change(old, before_version, changes);
    }
    /// Publishes one completed transaction made by the host or the vi engine.
    pub fn publish_direct_change(
        &mut self,
        old: vel_text::Text,
        before_version: vel_buffer::ChangeId,
        changes: ChangeSet,
    ) {
        if self.buffer.change_id() == before_version {
            return;
        }
        self.annotations.borrow_mut().change(
            &self.buffer,
            &self.settings,
            before_version,
            &changes,
        );
        self.fields_version = self
            .fields
            .as_ref()
            .map(|_| (self.buffer.id(), self.buffer.change_id()));
        if let Some(language) = self.language.borrow_mut().as_mut() {
            // Pure insertions without newlines leave overview row coordinates
            // valid. The guide row map is also identity. Retain both publications
            // while their worker catches up:
            // manufacturing provisional token widths scans growing line prefixes
            // on every key (and at every sampled caret line with many carets).
            // The worker receives the exact edit and publishes fresh geometry.
            let overview = (old.len_lines() == self.buffer.text().len_lines()
                && changes.changes().iter().all(|c| c.old_range.is_empty()))
            .then(|| {
                (
                    std::mem::take(&mut language.minimap),
                    std::mem::take(&mut language.guides),
                )
            });
            language.change(
                self.buffer.text().clone(),
                self.buffer.change_id(),
                changes.clone(),
                self.preferences.tab_size,
            );
            if let Some((overview, guides)) = overview {
                language.minimap = overview;
                language.guides = guides;
            }
        }
        self.status_column.borrow_mut().change(
            (self.buffer.id(), before_version),
            (self.buffer.id(), self.buffer.change_id()),
            &changes,
        );
        // A vi command can synchronize layout between its internal edits. Only
        // reuse geometry belonging to the transaction's actual starting version.
        self.layout
            .borrow_mut()
            .prepare_change((self.buffer.id(), before_version));
        self.layout.borrow_mut().change(
            &old,
            self.buffer.text(),
            (self.buffer.id(), self.buffer.change_id()),
            &changes,
        );
        // A sole view has already consumed this edit above. Retaining whole rope
        // roots for 64 generations only forces copying and retiring growing text.
        // Cloned/lazy views share this Rc and still need the bounded replay journal.
        if std::rc::Rc::strong_count(&self.layout_edits) > 1 {
            let mut shared = self.layout_edits.borrow_mut();
            shared.push_back(crate::editor::SharedLayoutEdit {
                buffer: self.buffer.id(),
                from: before_version,
                to: self.buffer.change_id(),
                before: old,
                after: self.buffer.text().clone(),
                changes,
            });
            while shared.len() > 64 {
                shared.pop_front();
            }
        } else {
            self.layout_edits.borrow_mut().clear();
        }
        self.layout_version = self.buffer.change_id();
    }
    fn replace_selections(&mut self, values: Vec<(String, Range<usize>)>, kind: EditKind) {
        let selection = self.buffer.view(self.id).sel();
        let mut delta = 0isize;
        let mut regions = Vec::new();
        let owned: Vec<_> = selection
            .iter()
            .zip(values)
            .map(|(r, (s, relative))| {
                let begin = r.begin().wrapping_add_signed(delta);
                regions.push(Region::new(begin + relative.start, begin + relative.end));
                delta += s.len() as isize - r.size() as isize;
                (r.to_range(), s)
            })
            .collect();
        let after = selection_primary(regions, selection.primary_index());
        self.apply_edits(owned, Some(after), kind);
    }
    pub fn language_command(&mut self, name: &str, args: &Value) -> Result<bool, String> {
        match name {
            "insert" => {
                let s = args["characters"]
                    .as_str()
                    .ok_or("insert needs characters")?;
                if s == "/"
                    && self.settings.bool("auto_close_tags", true)
                    && let Some(values) = self.closing_tag_values(TagClose::Slash)
                {
                    self.insert_typed(TypedInsert::PerCaret(&values));
                    return Ok(true);
                }
                let auto_newline = s == "\n" && args["literal"] != true;
                let bracket_columns = if auto_newline {
                    self.bracket_indents()
                } else {
                    Vec::new()
                };
                if auto_newline {
                    self.insert_indented_newline(&bracket_columns);
                    return Ok(true);
                }
                self.insert_typed(TypedInsert::Uniform(s));
                if s == "/" && self.settings.bool("auto_close_tags", true) {
                    let markup = self
                        .language
                        .borrow()
                        .as_ref()
                        .is_some_and(|l| l.closes_tags);
                    if markup
                        && self.regions().iter().any(|r| {
                            r.b >= 2
                                && self.buffer.text().is_char_boundary(r.b - 2)
                                && self.buffer.text().slice(r.b - 2..r.b) == "</"
                        })
                    {
                        self.defer_closing_tag(TagClose::Deferred);
                    }
                }
            }
            "close_tag" => {
                self.pending_closing_tag = None;
                if self.buffer.view(self.id).sel().iter().all(|r| !r.empty()) {
                    return Ok(true);
                }
                if let Some(values) = self.closing_tag_values(TagClose::Command) {
                    self.replace_selections(values, EditKind::Other);
                } else {
                    self.defer_closing_tag(TagClose::Command);
                }
            }
            "paste_and_indent" => {
                let clipboard = normalize_line_breaks(&self.clipboard);
                let whole_lines = last_copy(&clipboard).is_some_and(|c| c.whole_lines);
                let selection = self.buffer.view(self.id).sel().clone();
                let mut edits = Vec::new();
                let mut seen = std::collections::BTreeSet::new();
                for r in selection.iter() {
                    let row = self.text.byte_to_line(r.begin());
                    let start = self.text.line_to_byte(row);
                    let line = self.text.line(row).to_string();
                    let indent = &line[..line.len() - line.trim_start_matches([' ', '\t']).len()];
                    if whole_lines && r.empty() {
                        // Above the caret's line, at that line's indentation.
                        if seen.insert(start) {
                            edits.push((start..start, reindent_block(&clipboard, indent, false)));
                        }
                        continue;
                    }
                    // At the caret: inside the indentation the destination indentation is what
                    // precedes the caret; the first pasted line keeps its place on the line.
                    let before = &line[..(r.begin() - start).min(line.len())];
                    let at_indent = before.trim_start_matches([' ', '\t']).is_empty();
                    let dest = if at_indent { before } else { indent };
                    edits.push((r.to_range(), reindent_block(&clipboard, dest, true)));
                }
                self.apply_edits(edits, None, EditKind::Paste);
            }
            "paste" => {
                // Pasted text uses the buffer's LF line breaks whatever the source used.
                let clipboard = normalize_line_breaks(&self.clipboard);
                let selection = self.buffer.view(self.id).sel().clone();
                let count = selection.len();
                let copy = last_copy(&clipboard);
                let parts = copy
                    .as_ref()
                    .map(|c| c.parts.clone())
                    .filter(|parts| parts.len() == count);
                if copy.as_ref().is_some_and(|c| c.whole_lines)
                    && selection.iter().all(vel_buffer::Region::empty)
                {
                    // Whole lines copied without a selection go above each caret's line, and the
                    // carets stay with their text.
                    let mut edits = Vec::new();
                    for (i, r) in selection.iter().enumerate() {
                        let line = self.text.byte_to_line(r.b);
                        let start = self.text.line_to_byte(line);
                        let value = parts.as_ref().map_or(clipboard.as_str(), |p| &p[i]);
                        if edits
                            .last()
                            .is_some_and(|(at, _): &(usize, String)| *at == start)
                        {
                            continue;
                        }
                        edits.push((start, value.to_owned()));
                    }
                    let mut shift = 0;
                    let mut regions = Vec::new();
                    let mut k = 0;
                    for r in selection.iter() {
                        while k < edits.len() && edits[k].0 <= r.b {
                            shift += edits[k].1.len();
                            k += 1;
                        }
                        regions.push(vel_buffer::Region::caret(r.b + shift));
                    }
                    let owned = edits.into_iter().map(|(at, v)| (at..at, v)).collect();
                    self.apply_edits(
                        owned,
                        Some(Selection::from_regions(regions)),
                        EditKind::Paste,
                    );
                    return Ok(true);
                }
                if let Some(parts) = parts.filter(|_| count > 1) {
                    let values = parts
                        .into_iter()
                        .map(|s| {
                            let n = s.len();
                            (s, n..n)
                        })
                        .collect();
                    self.replace_selections(values, EditKind::Paste);
                    return Ok(true);
                }
                let lines: Vec<_> = clipboard.split('\n').collect();
                let values: Vec<_> = if count > 1 && lines.len() == count {
                    lines
                        .iter()
                        .map(|s| ((*s).to_owned(), s.len()..s.len()))
                        .collect()
                } else {
                    vec![(clipboard.clone(), clipboard.len()..clipboard.len()); count]
                };
                self.replace_selections(values, EditKind::Paste);
            }
            "left_delete" if args["decompose"] == true => {
                let edits = vel_buffer::ops::decomposing_deletions(&self.buffer, self.id);
                self.apply_edits(edits, None, EditKind::Delete);
            }
            "left_delete" | "right_delete" => {
                let mut ranges = Vec::new();
                for r in self.buffer.view(self.id).sel().iter() {
                    if !r.empty() {
                        ranges.push(r);
                        continue;
                    }
                    let mut at = if name == "right_delete" {
                        self.text.next_grapheme_boundary(r.b)
                    } else {
                        self.text.prev_grapheme_boundary(r.b)
                    };
                    // Preserve vel-buffer's tab-stop deletion while forwarding exact edits.
                    if name == "left_delete"
                        && self.preferences.translate_tabs_to_spaces
                        && self.preferences.use_tab_stops
                    {
                        let begin = self.text.line_to_byte(self.text.byte_to_line(r.b));
                        let prefix = self.text.slice(begin..r.b).to_string();
                        if !prefix.is_empty() && prefix.chars().all(|c| c == ' ' || c == '\t') {
                            let size = self.preferences.tab_size;
                            let target = (cells_with_tab(&prefix, size) - 1) / size * size;
                            let mut column = 0;
                            at = begin;
                            for c in prefix.chars() {
                                let next =
                                    column + if c == '\t' { size - column % size } else { 1 };
                                if next > target {
                                    break;
                                }
                                at += c.len_utf8();
                                column = next;
                            }
                        }
                    }
                    ranges.push(Region::new(r.b.min(at), r.b.max(at)));
                }
                let selection = Selection::from_regions(ranges);
                let trace = if name == "left_delete" {
                    self.trace_backspacing(&selection)
                } else {
                    None
                };
                self.apply_edits(
                    selection
                        .iter()
                        .map(|r| (r.to_range(), String::new()))
                        .collect(),
                    None,
                    EditKind::Delete,
                );
                if let Some(mut trace) = trace
                    && trace.lines.len() == self.buffer.view(self.id).sel().len()
                {
                    trace.version = self.buffer.change_id();
                    self.automatic_indents = Some(trace);
                }
            }
            "move_to" if args["to"] == "brackets" => self.bracket_command(false, args),
            "expand_selection"
                if matches!(
                    args["to"].as_str(),
                    Some("brackets" | "scope" | "tag" | "smart")
                ) =>
            {
                self.bracket_command(true, args)
            }
            "toggle_comment" => self.toggle_comment(args)?,
            "reindent" => self.start_reindent()?,
            "expand_tabs" | "unexpand_tabs" => {
                self.convert_leading_tabs(name == "expand_tabs", args)?
            }
            "detect_indentation" => {
                if let Some(indentation) = crate::language::detect_indentation(&self.text) {
                    indentation.apply(self);
                    self.sync();
                }
            }
            "fold" | "unfold" | "fold_by_level" | "unfold_all" | "fold_tag_attributes" => {
                self.fold_command(name, args)?
            }
            "select_lines" | "move"
                if name == "select_lines"
                    || matches!(args["by"].as_str(), Some("lines" | "pages")) =>
            {
                if self.layout.borrow().total() == 0 {
                    self.layout.borrow_mut().configure(
                        &self.text,
                        (self.buffer.id(), self.buffer.change_id()),
                        crate::layout::Options {
                            width: 0,
                            tab: self.preferences.tab_size,
                            indent: true,
                        },
                        &self.folded(),
                    );
                }
                let forward = args["forward"].as_bool().unwrap_or(false);
                let extend = args["extend"].as_bool().unwrap_or(false);
                let layout = self.layout.borrow();
                // The buffer's v1 VerticalLayout assumes LF line numbers. The view supplies
                // visual row numbers here while using the same x/offset/page contract.
                let old = self.buffer.view(self.id).sel();
                let mut regions = if name == "select_lines" {
                    old.iter().collect::<Vec<_>>()
                } else {
                    vec![]
                };
                regions.extend(old.iter().map(|r| {
                    let x = r.xpos.unwrap_or_else(|| layout.x_of(&self.text, r.b));
                    let row = layout.visual_at(&self.text, r.b).0;
                    let delta = if args["by"] == "pages" {
                        layout.lines_per_page()
                    } else {
                        1
                    };
                    let visual = if forward {
                        row.saturating_add(delta)
                            .min(layout.total().saturating_sub(1))
                    } else {
                        row.saturating_sub(delta)
                    };
                    let visual = layout.editable_visual(visual, forward);
                    let b = layout.offset_at(&self.text, visual, x);
                    // https://www.sublimetext.com/updates/2/stable/release_notes.html
                    // Only Up/Down at a document boundary, not Page or select-lines.
                    let b = if name == "move"
                        && args["by"] == "lines"
                        && row == visual
                        && self.settings.bool("move_to_limit_on_up_down", false)
                    {
                        if forward { self.text.len_bytes() } else { 0 }
                    } else {
                        b
                    };
                    let a = if name == "select_lines" && !r.empty() {
                        let row = layout.visual_at(&self.text, r.a).0;
                        let next = if forward {
                            (row + 1).min(layout.total().saturating_sub(1))
                        } else {
                            row.saturating_sub(1)
                        };
                        layout.offset_at(
                            &self.text,
                            layout.editable_visual(next, forward),
                            layout.x_of(&self.text, r.a),
                        )
                    } else if extend {
                        r.a
                    } else {
                        b
                    };
                    Region {
                        a,
                        b,
                        xpos: Some(x),
                    }
                }));
                let primary =
                    old.primary_index() + if name == "select_lines" { old.len() } else { 0 };
                let after = selection_primary(regions, primary);
                drop(layout);
                self.buffer.set_selection(self.id, after);
            }
            _ => return Ok(false),
        }
        Ok(true)
    }
    /// Breaks the line at every selection like `insert "\n"`, but a caret alone on a line that
    /// holds only indentation (typically left by the previous auto-indent) leaves that line
    /// empty instead of keeping trailing white space (`trim_automatic_white_space`).
    fn insert_indented_newline(&mut self, bracket_columns: &[Option<usize>]) {
        let selection = self.buffer.view(self.id).sel().clone();
        let track = self.fields.is_none() && self.language.borrow().is_some();
        let trim = self.settings.bool("trim_automatic_white_space", true);
        let mut delta = 0isize;
        let mut regions = Vec::new();
        let mut owned = Vec::new();
        let mut lines = Vec::new();
        let mut rules = HashMap::new();
        for (i, r) in selection.iter().enumerate() {
            let (text, relative, blank, rule) =
                self.newline_with_blank(r, bracket_columns.get(i).copied().flatten(), &mut rules);
            let mut range = r.to_range();
            // Selections are sorted and disjoint, so only the neighbours can share the row.
            if let Some(line) = blank.filter(|_| trim && r.empty()) {
                let row = self.text.byte_to_line(r.b);
                let on_row = |o: Option<Region>, end: bool| {
                    o.is_some_and(|o| {
                        self.text
                            .byte_to_line(if end { o.end() } else { o.begin() })
                            == row
                    })
                };
                if !on_row(i.checked_sub(1).and_then(|p| selection.get(p)), true)
                    && !on_row(selection.get(i + 1), false)
                {
                    range = line;
                }
            }
            let begin = (range.start as isize + delta) as usize;
            regions.push(Region::new(begin + relative.start, begin + relative.end));
            if track {
                lines.push(
                    rule.map(|reduction| (begin + relative.end, relative.end - 1, reduction)),
                );
            }
            delta += text.len() as isize - range.len() as isize;
            owned.push((range, text));
        }
        let after = selection_primary(regions, selection.primary_index());
        self.apply_edits(owned, Some(after), EditKind::InsertChars);
        // Validate the destination, not the last token on the old line: a
        // heredoc, for example, can start only after the newline. The existing
        // exact-scope budget applies; unclassified destinations never dedent.
        let points: Vec<_> = lines.iter().flatten().map(|&(next, _, _)| next).collect();
        let Some(scopes) = (!points.is_empty())
            .then(|| {
                self.exact_scopes(&points).or_else(|| {
                    let row = self.last_bounded_scope_row()?;
                    let count =
                        points.partition_point(|&p| self.buffer.text().byte_to_line(p) <= row);
                    (count > 0 && count < points.len())
                        .then(|| self.exact_scopes(&points[..count]))
                        .flatten()
                })
            })
            .flatten()
        else {
            self.automatic_indents = None;
            return;
        };
        let mut scopes = scopes.into_iter();
        let language = self.language.borrow();
        let mut rules = HashMap::new();
        let comment = scope_named("comment");
        let mut grouped = HashMap::new();
        let mut groups = Vec::new();
        let text = self.buffer.text();
        let lines: Vec<_> = lines
            .into_iter()
            .map(|line| {
                let (next, indent_bytes, reduction) = line?;
                let stack = scopes.next()?;
                let l = language.as_ref()?;
                let rule = rules
                    .entry(stack)
                    .or_insert_with_key(|stack| {
                        if stack.is_empty()
                            || vel_syntax::indent::is_string_or_heredoc(stack)
                            || stack.iter().any(|&s| comment.is_prefix_of(s))
                        {
                            return None;
                        }
                        let metadata = l
                            .assets
                            .metadata
                            .metadata_for(&vel_scope::ScopeStack::from_vec(stack.clone()));
                        l.assets
                            .metadata
                            .pattern(&metadata, "decreaseIndentPattern")
                            .filter(|re| re.compile_error().is_none())
                    })
                    .clone()?;
                let row = text.byte_to_line(next);
                let end = text.line_to_byte(row) + text.line_len_bytes(row);
                if end - (next - indent_bytes) >= DEDENT_LIMIT {
                    return None;
                }
                // Metadata shares immutable regex source strings. The groups own
                // the regexes for the lifetime of this temporary grouping index.
                let key = (
                    text.slice(next - indent_bytes..next).to_string(),
                    indentation(reduction, &self.preferences),
                    text.slice(next..end).to_string(),
                    rule.regex_str() as *const str,
                );
                let group = match grouped.entry(key) {
                    std::collections::hash_map::Entry::Occupied(entry) => *entry.get(),
                    std::collections::hash_map::Entry::Vacant(entry) => {
                        let (original, reduced, suffix, _) = entry.key();
                        groups.push(IndentGroup {
                            seed: IndentSeed {
                                original: original.clone(),
                                reduced: reduced.clone(),
                                suffix: suffix.clone(),
                                rule,
                            },
                            typed: String::with_capacity(16),
                            dedented: false,
                        });
                        *entry.insert(groups.len() - 1)
                    }
                };
                Some(IndentedCaret { next, group })
            })
            .collect();
        self.automatic_indents = (!groups.is_empty()
            && lines.len() == self.buffer.view(self.id).sel().len())
        .then(|| AutomaticIndents {
            buffer: self.buffer.id(),
            version: self.buffer.change_id(),
            settings: self.settings.revision(),
            lines,
            steps: Vec::with_capacity(groups.len()),
            groups,
            scratch: String::with_capacity(DEDENT_LIMIT),
        });
    }

    fn trace_backspacing(&mut self, deletions: &Selection) -> Option<AutomaticIndents> {
        let selections = self.buffer.view(self.id).sel();
        let mut trace = self.automatic_indents.take().filter(|trace| {
            trace.buffer == self.buffer.id()
                && trace.version == self.buffer.change_id()
                && trace.settings == self.settings.revision()
                && trace.lines.len() == selections.len()
                && deletions.len() == selections.len()
                && self.fields.is_none()
        })?;
        let mut deleted = 0;
        let mut grouped = HashMap::new();
        let old_groups = std::mem::take(&mut trace.groups);
        for ((line, old), edit) in trace
            .lines
            .iter_mut()
            .zip(selections.iter())
            .zip(deletions.iter())
        {
            if !old.empty()
                || edit.end() != old.b
                || self.text.byte_to_line(edit.begin()) != self.text.byte_to_line(old.b)
            {
                return None;
            }
            *line = line.and_then(|caret| {
                let group = &old_groups[caret.group];
                let len = group.typed.len().checked_sub(edit.size())?;
                if old.b != caret.next || !group.typed.is_char_boundary(len) || edit.empty() {
                    return None;
                }
                let group = *grouped.entry((caret.group, len)).or_insert_with(|| {
                    let mut group = group.clone();
                    // Keep the visible indentation as-is on Backspace. The next
                    // insertion can compare its complete, corrected prefix again.
                    group.typed.truncate(len);
                    trace.groups.push(group);
                    trace.groups.len() - 1
                });
                Some(IndentedCaret {
                    next: edit.begin() - deleted,
                    group,
                })
            });
            deleted += edit.size();
        }
        (!trace.groups.is_empty()).then_some(trace)
    }
    /// New whitespace and caret, an optional blank line to trim, and possible reduced indent.
    fn newline_with_blank(
        &self,
        r: Region,
        bracket_column: Option<usize>,
        rules: &mut HashMap<vel_scope::ScopeStack, NewlineRules>,
    ) -> IndentedNewline {
        let row = self.text.byte_to_line(r.begin());
        if self.text.line_len_bytes(row) >= crate::large::LONG_LINE {
            return ("\n".into(), 1..1, None, None);
        }
        if !self.settings.bool("auto_indent", true) {
            return ("\n".into(), 1..1, None, None);
        }
        let start = self.text.line_to_byte(row);
        let line = self.text.line(row).to_string();
        let blank = (!line.is_empty() && line.bytes().all(|b| matches!(b, b' ' | b'\t')))
            .then(|| start..start + line.len());
        let prefix = &line[..r.begin() - start];
        let leading = &prefix[..prefix.len() - prefix.trim_start_matches([' ', '\t']).len()];
        let mut indent = cells_with_tab(leading, self.preferences.tab_size);
        let after_row = self.text.byte_to_line(r.end());
        let after = if after_row == row {
            Cow::Borrowed(&line[r.end() - start..])
        } else {
            let end = self.text.line_to_byte(after_row) + self.text.line_len_bytes(after_row);
            Cow::Owned(self.text.slice(r.end()..end).to_string())
        };
        let language = self.language.borrow();
        let mut increase = false;
        let mut decrease = false;
        let mut temporary_previous = false;
        let mut excluded = false;
        let mut can_dedent = false;
        let smart = self.settings.bool("smart_indent", true);
        if let Some(l) = language.as_ref().filter(|_| smart) {
            let scopes = l.scopes(&self.text, r.begin().saturating_sub(1));
            let rule = rules
                .entry(scopes)
                .or_insert_with_key(|s| NewlineRules::new(l, s));
            let matches = |pattern: &Option<IndentRule>, text| {
                pattern.as_ref().is_some_and(|p| p.is_match(text))
            };
            excluded = matches(&rule.excluded, prefix);
            if !excluded && !matches(&rule.disabled, prefix) {
                increase = matches(&rule.increase, prefix) || matches(&rule.bracket, prefix);
                // An unmatched opening delimiter supplements metadata for code syntaxes.
                if rule.code && prefix.trim_end().ends_with(['{', '[', '(']) {
                    increase = true;
                }
                decrease = matches(&rule.decrease, &after)
                    || (rule.code && after.trim_start().starts_with(['}', ']', ')']));
                if row > 0 && rule.bracket.is_some() {
                    let previous = self.text.line(row - 1).to_string();
                    let previous = previous.trim_end();
                    temporary_previous =
                        matches(&rule.bracket, previous) && !matches(&rule.increase, previous);
                }
                can_dedent = rule.decrease.is_some();
            }
        }
        if excluded {
            indent = 0;
        } else if increase {
            indent += self.preferences.tab_size;
        } else if temporary_previous {
            indent = indent.saturating_sub(self.preferences.tab_size);
        }
        // https://www.sublimetext.com/docs/indentation.html#automatic-indentation-settings
        if !excluded && let Some(column) = bracket_column {
            indent = column;
            increase = false;
        }
        let whitespace = |n: usize| indentation(n, &self.preferences);
        let mut text = format!("\n{}", whitespace(indent));
        let caret = text.len();
        if increase && decrease {
            text.push('\n');
            text.push_str(&whitespace(
                indent.saturating_sub(self.preferences.tab_size),
            ));
        }
        let reduction = indent.saturating_sub(self.preferences.tab_size);
        (
            text,
            caret..caret,
            blank,
            (can_dedent && reduction != indent).then_some(reduction),
        )
    }

    fn insert_typed(&mut self, input: TypedInsert<'_>) {
        if self.fields.is_some() {
            self.automatic_indents = None;
            let count = self.buffer.view(self.id).sel().len();
            let values = (0..count)
                .map(|i| {
                    let (text, relative) = input.at(i);
                    (text.to_owned(), relative)
                })
                .collect();
            self.replace_selections(values, EditKind::InsertChars);
            return;
        }
        let uniform = matches!(input, TypedInsert::Uniform(_));
        let selection = self.buffer.view(self.id).sel();
        let mut trace = self.automatic_indents.take().filter(|trace| {
            trace.buffer == self.buffer.id()
                && trace.version == self.buffer.change_id()
                && trace.settings == self.settings.revision()
                && selection.len() == trace.lines.len()
        });
        let mut steps = Vec::new();
        if let Some(trace) = &mut trace {
            std::mem::swap(&mut steps, &mut trace.steps);
            steps.clear();
            if let TypedInsert::Uniform(s) = input {
                // Identical candidates share one regex match and adjustment, even
                // in a stale scope generation with thousands of carets.
                steps.extend(
                    trace
                        .groups
                        .iter_mut()
                        .map(|g| g.advance(s, &mut trace.scratch)),
                );
            } else {
                // A generated tag may differ per caret or advance past existing text.
                // Apply the same rule once, then stop tracking that typing run.
                steps.extend(trace.lines.iter().enumerate().map(|(i, line)| {
                    line.map_or(IndentStep::Stop, |line| {
                        trace.groups[line.group]
                            .clone()
                            .advance(input.at(i).0, &mut trace.scratch)
                    })
                }));
            }
        }
        let mut delta = 0isize;
        let mut regions = Vec::with_capacity(selection.len());
        let mut edits = Vec::with_capacity(selection.len());
        let mut previous_end = 0;
        let mut adjusted = false;
        let mut keep_trace = false;
        for (i, r) in selection.iter().enumerate() {
            let (mut value, mut relative) = input.at(i);
            let mut range = r.to_range();
            if let Some(trace) = &mut trace {
                let line = &mut trace.lines[i];
                if let Some(caret) = line.as_mut().filter(|l| r.empty() && l.next == r.b) {
                    let step = &steps[if uniform { caret.group } else { i }];
                    let keep = match step {
                        IndentStep::Stop => false,
                        IndentStep::Unchanged => true,
                        IndentStep::Adjust { remove, text } => {
                            let start = r.b - remove;
                            if start >= previous_end {
                                range.start = start;
                                let prefix = text.len() - value.len();
                                relative.start += prefix;
                                relative.end += prefix;
                                value = text;
                                adjusted = true;
                                true
                            } else {
                                false
                            }
                        }
                    };
                    if keep && uniform {
                        caret.next = range.start.wrapping_add_signed(delta) + relative.end;
                        keep_trace = true;
                    } else {
                        *line = None;
                    }
                } else {
                    *line = None;
                }
            }
            let at = range.start.wrapping_add_signed(delta);
            regions.push(Region::new(at + relative.start, at + relative.end));
            delta += value.len() as isize - range.len() as isize;
            previous_end = range.end;
            let edit = Edit { range, text: value };
            if edit.range.is_empty() && !value.is_empty() || !self.buffer.edit_is_noop(&edit) {
                edits.push(edit);
            }
        }
        let after = selection_primary(regions, selection.primary_index());
        self.transact_direct(
            &edits,
            after,
            if adjusted {
                EditKind::Other
            } else {
                EditKind::InsertChars
            },
        );
        if keep_trace
            && let Some(mut trace) = trace
            && trace.lines.len() == self.buffer.view(self.id).sel().len()
        {
            trace.version = self.buffer.change_id();
            trace.steps = steps;
            self.automatic_indents = Some(trace);
        }
    }
    /// Alignment inspects at most 64 lines / 8 KiB backwards per caret.
    fn bracket_indents(&self) -> Vec<Option<usize>> {
        if !self.settings.bool("auto_indent", true)
            || !self.settings.bool("indent_to_bracket", false)
        {
            return Vec::new();
        }
        let regions = self.regions();
        let eligible: Vec<_> = regions
            .iter()
            .map(|r| {
                let row = self.text.byte_to_line(r.begin());
                r.begin() - self.text.line_to_byte(row) <= 8192
                    && self.text.line_len_bytes(row) <= 8192
            })
            .collect();
        let Some(end) = regions
            .iter()
            .zip(&eligible)
            .filter(|(_, ok)| **ok)
            .map(|(r, _)| r.begin())
            .max()
        else {
            return Vec::new();
        };
        // Warm a small stale prefix once for the whole batch, or keep ordinary indentation.
        if self.bounded_scopes(&[end]).is_none() {
            return Vec::new();
        }
        regions
            .iter()
            .zip(eligible)
            .map(|(r, eligible)| {
                if !eligible {
                    return None;
                }
                let row = self.text.byte_to_line(r.begin());
                let start = self
                    .text
                    .line_to_byte(row.saturating_sub(64))
                    .max(self.text.ceil_char_boundary(r.begin().saturating_sub(8192)));
                let mut close = Vec::new();
                let mut at = r.begin();
                for c in self.text.slice(start..r.begin()).chars().rev() {
                    at -= c.len_utf8();
                    if !matches!(c, '(' | ')' | '[' | ']') {
                        continue;
                    }
                    let scopes = self.bounded_scopes(&[at])?;
                    if scopes[0]
                        .iter()
                        .any(|s| scope_prefix("string", *s) || scope_prefix("comment", *s))
                    {
                        continue;
                    }
                    match c {
                        ')' | ']' => close.push(c),
                        '(' | '[' if !close.is_empty() => {
                            if close.pop() != Some(if c == '(' { ')' } else { ']' }) {
                                return None;
                            }
                        }
                        _ => {
                            let line = self.text.byte_to_line(at);
                            let end = if line + 1 < self.text.len_lines() {
                                self.text.line_to_byte(line + 1)
                            } else {
                                self.text.len_bytes()
                            };
                            // A bracket at EOL uses normal hanging indentation. Immediate pairs
                            // retain the existing two-line Enter expansion.
                            let after = self.text.slice(at + 1..end);
                            let first = after.chars().find(|c| !c.is_whitespace())?;
                            if first == if c == '(' { ')' } else { ']' } {
                                return None;
                            }
                            let begin = self.text.line_to_byte(line);
                            if at - begin > 8192 {
                                return None;
                            }
                            return Some(cells_with_tab(
                                &self.text.slice(begin..at + 1).to_string(),
                                self.preferences.tab_size,
                            ));
                        }
                    }
                }
                None
            })
            .collect()
    }
    /// Only markup enters the bounded scan; cold large documents wait for exact scopes.
    fn closing_tag_values(&self, mode: TagClose) -> Option<Vec<(String, Range<usize>)>> {
        // HTML/XML only: https://sublime-text-unofficial-documentation.readthedocs.io/en/latest/reference/settings.html
        // Scope names: https://www.sublimetext.com/docs/scope_naming.html
        let language = self.language.borrow();
        let language = language.as_ref()?;
        let caret = self.caret;
        let published = language.scope_snapshot_at(caret);
        let markup = |scopes: &[vel_scope::Scope]| {
            scopes
                .iter()
                .any(|s| scope_prefix("text.html", *s) || scope_prefix("text.xml", *s))
        };
        use vel_highlight::ScopeProvider;
        if !language.closes_tags
            && !published
                .as_ref()
                .and_then(|s| s.scopes_at(caret))
                .is_some_and(markup)
        {
            return None;
        }
        let regions = self.regions();
        let scopes_at = |at| {
            if mode == TagClose::Command {
                language
                    .scope_snapshot_at(at)?
                    .scopes_at(at)
                    .map(<[_]>::to_vec)
            } else {
                self.bounded_scopes(&[at])?.pop()
            }
        };
        let point = |r: &Region| {
            let prefix = match mode {
                TagClose::Slash => "<",
                TagClose::Deferred => "</",
                TagClose::Command => "",
            };
            let at = r.b.checked_sub(prefix.len())?;
            (r.empty() && self.text.is_char_boundary(at) && self.text.slice(at..r.b) == prefix)
                .then_some(at)
        };
        let last = regions.iter().filter_map(point).max()?;
        scopes_at(last)?;
        let mut unavailable = false;
        let values = regions
            .iter()
            .map(|r| {
                let plain = || {
                    if mode == TagClose::Command && !r.empty() {
                        return (
                            self.text.slice(r.to_range()).to_string(),
                            r.a - r.begin()..r.b - r.begin(),
                        );
                    }
                    let s: String = if mode == TagClose::Slash { "/" } else { "" }.into();
                    let end = s.len();
                    (s, end..end)
                };
                let Some(lt) = point(r) else {
                    return plain();
                };
                let Some(scopes) = scopes_at(lt) else {
                    unavailable = true;
                    return plain();
                };
                if !tag_scopes(&scopes) {
                    return plain();
                }
                let html = scopes.iter().any(|s| scope_prefix("text.html", *s));
                let row = self.text.byte_to_line(lt);
                let start = self
                    .text
                    .line_to_byte(row.saturating_sub(128))
                    .max(self.text.ceil_char_boundary(lt.saturating_sub(16 * 1024)));
                let mut closed: Vec<&str> = Vec::new();
                let source = self.text.slice(start..lt).to_string();
                for (offset, _) in source.rmatch_indices('<') {
                    let at = start + offset;
                    let rest = &source[offset + 1..];
                    let closing = rest.starts_with('/');
                    let rest = rest.strip_prefix('/').unwrap_or(rest);
                    let width = rest
                        .find(|c: char| !c.is_alphanumeric() && !matches!(c, '_' | ':' | '-' | '.'))
                        .unwrap_or(rest.len());
                    if width == 0
                        || !rest
                            .chars()
                            .next()
                            .is_some_and(|c| c.is_alphabetic() || c == '_')
                    {
                        continue;
                    }
                    let name = &rest[..width];
                    let name_at = at + 1 + usize::from(closing);
                    let Some(scopes) = scopes_at(name_at) else {
                        unavailable = true;
                        return plain();
                    };
                    // A lexical `<` inside code, raw markup, attributes or comments is not a tag.
                    if !tag_scopes(&scopes)
                        || !scopes.iter().any(|s| {
                            scope_prefix("entity.name.tag", *s) || scope_prefix("meta.tag", *s)
                        })
                    {
                        continue;
                    }
                    let mut quote = None;
                    let mut end = None;
                    for (i, c) in rest[width..].char_indices() {
                        if quote == Some(c) {
                            quote = None;
                        } else if quote.is_none() {
                            match c {
                                '\'' | '"' => quote = Some(c),
                                '>' => {
                                    end = Some(width + i);
                                    break;
                                }
                                '<' => break,
                                _ => (),
                            }
                        }
                    }
                    let Some(end) = end else {
                        continue;
                    };
                    // https://www.sublimetext.com/3 (3033): skip self-closing tags.
                    if !closing
                        && (rest[..end].trim_end().ends_with('/') || html && html_void_tag(name))
                    {
                        continue;
                    }
                    if closing {
                        closed.push(name);
                    } else if closed.last().is_some_and(|last| {
                        if html {
                            last.eq_ignore_ascii_case(name)
                        } else {
                            *last == name
                        }
                    }) {
                        closed.pop();
                    } else if closed.is_empty() {
                        let existing = mode != TagClose::Command
                            && self.text.slice(r.b..self.text.len_bytes()).chars().next()
                                == Some('>');
                        let value = format!(
                            "{}{}{}",
                            match mode {
                                TagClose::Slash => "/",
                                TagClose::Deferred => "",
                                TagClose::Command => "</",
                            },
                            name,
                            if existing { "" } else { ">" }
                        );
                        let caret = value.len() + usize::from(existing);
                        return (value, caret..caret);
                    }
                }
                plain()
            })
            .collect();
        if unavailable { None } else { Some(values) }
    }
    fn defer_closing_tag(&mut self, mode: TagClose) {
        if let Some(language) = self.language.borrow().as_ref().filter(|l| l.closes_tags) {
            self.pending_closing_tag = Some(PendingClosingTag {
                buffer: self.buffer.id(),
                version: self.buffer.change_id(),
                selection: self.regions(),
                root: language.root,
                mode,
            });
        }
    }
    /// Complete a deferred tag only while its revision, selection and syntax still agree.
    pub(crate) fn poll_closing_tag(&mut self) -> bool {
        let Some(pending) = self.pending_closing_tag.take() else {
            return false;
        };
        if pending.buffer != self.buffer.id()
            || pending.version != self.buffer.change_id()
            || pending.selection != self.regions()
            || self.read_only
            || self.marked.is_some()
            || pending.mode == TagClose::Deferred && !self.settings.bool("auto_close_tags", true)
            || !self
                .language
                .borrow()
                .as_ref()
                .is_some_and(|language| language.root == pending.root)
        {
            return false;
        }
        if let Some(values) = self.closing_tag_values(pending.mode) {
            if values.iter().any(|(text, _)| !text.is_empty()) {
                if pending.mode == TagClose::Command {
                    self.replace_selections(values, EditKind::Other);
                } else {
                    self.insert_typed(TypedInsert::PerCaret(&values));
                }
                self.sync();
                return true;
            }
        } else {
            self.pending_closing_tag = Some(pending);
        }
        false
    }
    /// A leaving view may finish within the typing budget, but can never edit later.
    pub(crate) fn finish_closing_tag_on_leave(&mut self) {
        self.poll_closing_tag();
        self.pending_closing_tag = None;
    }
    fn bracket_command(&mut self, expand: bool, args: &Value) {
        let language = self.language.borrow();
        let old = self.buffer.view(self.id).sel();
        let regions = old
            .iter()
            .map(|r| {
                let pairs = if expand && args["to"].as_str() == Some("scope") {
                    Vec::new()
                } else {
                    crate::language::command_pairs(
                        language.as_ref(),
                        &self.text,
                        if expand { r.begin() } else { r.b },
                    )
                };
                if !expand {
                    let pair = pairs
                        .iter()
                        .filter(|p| p.kind != '<')
                        .filter(|p| p.open.start <= r.b && r.b <= p.close.end)
                        .min_by_key(|p| {
                            let priority = if p.open.contains(&r.b) || p.close.contains(&r.b) {
                                0
                            } else if p.open.end == r.b || p.close.end == r.b {
                                1
                            } else {
                                2
                            };
                            (priority, p.close.end - p.open.start)
                        });
                    return pair.map_or(r, |p| {
                        let at = if p.close.contains(&r.b) || r.b == p.close.end {
                            p.open.start
                        } else {
                            p.close.start
                        };
                        Region::new(
                            if args["extend"].as_bool().unwrap_or(false) {
                                r.a
                            } else {
                                at
                            },
                            at,
                        )
                    });
                }
                let target = args["to"].as_str().unwrap_or("brackets");
                let mut candidates = Vec::new();
                if matches!(target, "scope" | "smart")
                    && let Some(l) = language.as_ref()
                {
                    candidates.extend(crate::language::command_scope_regions(l, r.begin(), ""));
                }
                if target == "scope" && language.is_none() {
                    candidates.push(0..self.text.len_bytes());
                }
                for pair in pairs.iter().filter(|p| {
                    if target == "scope" {
                        false
                    } else if target == "tag" {
                        p.kind == 't'
                    } else {
                        p.kind != '<' && (target == "smart" || p.kind != 't')
                    }
                }) {
                    candidates.push(pair.open.end..pair.close.start);
                    candidates.push(pair.open.start..pair.close.end);
                }
                candidates
                    .into_iter()
                    .filter(|c| {
                        c.start <= r.begin()
                            && r.end() <= c.end
                            && (c.start < r.begin() || r.end() < c.end)
                    })
                    .min_by_key(|c| c.len())
                    .map_or(r, |c| {
                        if r.a <= r.b {
                            Region::new(c.start, c.end)
                        } else {
                            Region::new(c.end, c.start)
                        }
                    })
            })
            .collect();
        let after = selection_primary(regions, old.primary_index());
        drop(language);
        self.buffer.set_selection(self.id, after);
    }
    fn toggle_comment(&mut self, args: &Value) -> Result<(), String> {
        let block = args["block"].as_bool().unwrap_or(false);
        let variant = args["variant"].as_u64().filter(|&n| n > 0);
        let language = self.language.borrow();
        // Comment markers come from syntax metadata:
        // https://docs.sublimetext.io/reference/comments.html
        let Some(l) = language.as_ref() else {
            drop(language);
            self.actions.push((
                "command_note".into(),
                json!({"message":"Comments are not available in this syntax."}),
            ));
            return Ok(());
        };
        let selection = self.buffer.view(self.id).sel();
        // Share the bounded prefix across carets instead of extending it once
        // for every stale line in a multi-caret command.
        if selection.len() > 1
            && let Some(limit) = self.last_bounded_scope_row()
            && let Some(row) = selection.iter().rev().find_map(|r| {
                let row = self.text.byte_to_line(r.begin());
                (row <= limit && !l.scopes_ready_at(&self.text, r.begin())).then_some(row)
            })
        {
            let _ = self.exact_scope_prefix(l, row);
        }
        let mut edits = BTreeMap::new();
        let mut enclosed = Vec::new();
        let mut rows = BTreeMap::new();
        for region in selection.iter() {
            let scope = if l.scopes_ready_at(&self.text, region.begin()) {
                l.scopes(&self.text, region.begin())
            } else {
                self.exact_scopes(&[region.begin()])
                    .and_then(|mut scopes| scopes.pop())
                    .map(vel_scope::ScopeStack::from_vec)
                    .unwrap_or_else(|| l.scopes(&self.text, region.begin()))
            };
            let m = l.assets.metadata.metadata_for(&scope);
            let mut delimiters = Vec::new();
            // Numbered marker sets: https://docs.sublimetext.io/reference/comments.html
            // variant argument: https://www.sublimetext.com/dev (build 4130).
            for (key, start) in &m.shell_variables {
                let Some(suffix) = key.strip_prefix("TM_COMMENT_START") else {
                    continue;
                };
                let number: Option<u64> = if suffix.is_empty() {
                    Some(1)
                } else {
                    suffix.strip_prefix('_').and_then(|s| s.parse().ok())
                };
                let Some(number) = number.filter(|&n| n > 0 && !start.is_empty()) else {
                    continue;
                };
                let get = |key: &str| m.shell_variables.get(&format!("{key}{suffix}"));
                let end = get("TM_COMMENT_END").cloned().unwrap_or_default();
                let column_zero =
                    get("TM_COMMENT_DISABLE_INDENT").is_some_and(|s| s.eq_ignore_ascii_case("yes"));
                // https://www.sublimetext.com/download (build 4166).
                let insensitive = get("TM_COMMENT_CASE_INSENSITIVE")
                    .or_else(|| m.shell_variables.get("TM_COMMENT_CASE_INSENSITIVE"))
                    .is_some_and(|s| {
                        s.eq_ignore_ascii_case("yes") || s.eq_ignore_ascii_case("true")
                    });
                delimiters.push(CommentMarker {
                    number,
                    start: start.clone(),
                    end,
                    column_zero,
                    insensitive,
                });
            }
            delimiters.sort_by_key(|m| m.number);
            let blocks = || delimiters.iter().filter(|m| !m.end.is_empty());
            let lines = || delimiters.iter().filter(|m| m.end.is_empty());
            let preferred = delimiters
                .iter()
                .find(|m| Some(m.number) == variant && (!block || !m.end.is_empty()))
                .or_else(|| if block { None } else { lines().next() })
                .or_else(|| blocks().next());
            if blocks().next().is_some()
                && let Some(comment) = self.enclosing_block_comment(l, region)
            {
                let source = self.text.slice(comment.clone()).to_string();
                let row = self.text.byte_to_line(comment.start);
                let start = self.text.line_to_byte(row);
                let wrapped_line = region.empty()
                    && !block
                    && comment.start == start
                    && comment.end == start + self.text.line_len_bytes(row);
                let padded = (wrapped_line || lines().next().is_none()) && !source.contains('\n');
                if let Some((start_len, end_len)) = blocks()
                    .filter_map(|m| m.enclosing_lengths(&source, padded))
                    .max()
                {
                    edits.insert((comment.start, comment.start + start_len), String::new());
                    edits.insert((comment.end - end_len, comment.end), String::new());
                    continue;
                }
            }
            let Some(preferred) = preferred else {
                drop(language);
                self.actions.push((
                    "command_note".into(),
                    json!({"message":"This syntax does not support that kind of comment."}),
                ));
                return Ok(());
            };
            let touched = || {
                let first = self.text.byte_to_line(region.begin());
                let last = self
                    .text
                    .byte_to_line(region.end().saturating_sub(usize::from(!region.empty())));
                first..=last
            };
            if !block && !preferred.end.is_empty() && lines().next().is_some() {
                // A requested insertion variant can be a block marker even though
                // this selection is already commented with line markers.
                let existing: Option<Vec<_>> = touched()
                    .filter_map(|row| {
                        let line = self.text.line(row).to_string();
                        let body = line.trim_start_matches([' ', '\t']);
                        if body.trim().is_empty() {
                            return None;
                        }
                        let start = self.text.line_to_byte(row) + line.len() - body.len();
                        Some(
                            lines()
                                .filter_map(|m| m.line_marker_len(body))
                                .max()
                                .map(|len| (start, start + len)),
                        )
                    })
                    .collect();
                if let Some(existing) = existing.filter(|ranges| !ranges.is_empty()) {
                    edits.extend(existing.into_iter().map(|range| (range, String::new())));
                    continue;
                }
            }
            if !preferred.end.is_empty() || variant.is_some() && blocks().next().is_some() {
                let whole_line = region.empty() && !block;
                let row = self.text.byte_to_line(region.b);
                let a = if whole_line {
                    self.text.line_to_byte(row)
                } else {
                    region.begin()
                };
                let b = if whole_line {
                    a + self.text.line(row).len_bytes()
                } else {
                    region.end()
                };
                let selected = self.text.slice(a..b).to_string();
                if let Some((left, right)) = blocks()
                    .filter_map(|m| m.enclosing_lengths(&selected, whole_line))
                    .max()
                {
                    edits.insert((a, a + left), String::new());
                    edits.insert((b - right, b), String::new());
                    continue;
                } else if let Some((left, right)) = blocks()
                    .filter_map(|m| {
                        let (left, right) = (m.start.len(), m.end.len());
                        let open = a.checked_sub(left)?;
                        let close = b + right;
                        (close <= self.text.len_bytes()
                            && self.text.is_char_boundary(open)
                            && self.text.is_char_boundary(close)
                            && m.starts(&self.text.slice(open..a).to_string(), &m.start)
                            && m.starts(&self.text.slice(b..close).to_string(), &m.end))
                        .then_some((left, right))
                    })
                    .max()
                {
                    edits.insert((a - left, a), String::new());
                    edits.insert((b, b + right), String::new());
                    continue;
                } else if !preferred.end.is_empty() {
                    let (start, end) = (&preferred.start, &preferred.end);
                    let (left, right) = if whole_line {
                        (
                            format!("{} ", start.trim_end()),
                            format!(" {}", end.trim_start()),
                        )
                    } else {
                        (start.clone(), end.clone())
                    };
                    // Insert separate delimiters to preserve carets and selection interiors.
                    if a == b {
                        edits.insert((a, b), format!("{left}{right}"));
                    } else {
                        edits.insert((a, a), left.clone());
                        edits.insert((b, b), right);
                    }
                    if !whole_line || a == b {
                        enclosed.push((region, left.len()));
                    }
                    continue;
                }
            }
            let alternatives: std::rc::Rc<[_]> = lines().cloned().collect::<Vec<_>>().into();
            for row in touched() {
                rows.entry(row)
                    .or_insert_with(|| (preferred.clone(), alternatives.clone()));
            }
        }
        // A mixed selection is commented uniformly; a fully commented one is uncommented. Blank
        // lines are never commented, so they do not count either way.
        let remove = rows.iter().all(|(row, (_, markers))| {
            let line = self.text.line(*row).to_string();
            line.trim().is_empty()
                || markers.iter().any(|m| {
                    m.line_marker_len(line.trim_start_matches([' ', '\t']))
                        .is_some()
                })
        });
        for (row, (preferred, markers)) in rows {
            let line = self.text.line(row).to_string();
            let indent = line.len() - line.trim_start_matches([' ', '\t']).len();
            if line.trim().is_empty() {
                continue;
            }
            let start = self.text.line_to_byte(row);
            let byte = start + indent;
            if remove {
                if let Some(count) = markers
                    .iter()
                    .filter_map(|m| m.line_marker_len(&line[indent..]))
                    .max()
                {
                    edits.insert((byte, byte + count), String::new());
                }
            } else {
                let byte = if preferred.column_zero { start } else { byte };
                edits.insert((byte, byte), preferred.start);
            }
        }
        drop(language);
        let after = if enclosed.is_empty() {
            None
        } else {
            let changes = ChangeSet::new(
                edits
                    .iter()
                    .map(|((a, b), s)| Change {
                        old_range: *a..*b,
                        new_len: s.len(),
                    })
                    .collect(),
            );
            let old = self.buffer.view(self.id).sel();
            Some(selection_primary(
                old.iter()
                    .map(|r| {
                        if let Some((_, prefix)) = enclosed.iter().find(|(old, _)| *old == r) {
                            let a = changes.transform_point(r.begin(), Bias::Left) + prefix;
                            let b = a + r.size();
                            if r.a <= r.b {
                                Region::new(a, b)
                            } else {
                                Region::new(b, a)
                            }
                        } else {
                            Region::new(
                                changes.transform_point(r.a, Bias::Right),
                                changes.transform_point(r.b, Bias::Right),
                            )
                        }
                    })
                    .collect(),
                old.primary_index(),
            ))
        };
        self.apply_edits(
            edits.into_iter().map(|((a, b), s)| (a..b, s)).collect(),
            after,
            EditKind::Other,
        );
        Ok(())
    }
    /// Convert only leading whitespace in one old-coordinate transaction. Tabs advance
    /// to visual tab stops; spaces after code and inside strings remain byte-identical.
    fn convert_leading_tabs(&mut self, spaces: bool, args: &Value) -> Result<(), String> {
        let size = self.preferences.tab_size.max(1);
        let language = self.language.borrow();
        if language.is_none() {
            return Err("Could not convert indentation for this document.".into());
        }
        // Commands can precede the first highlight publication or follow an edit in
        // the same event turn. Parse this exact document version, as reindent does,
        // rather than treating unavailable scopes as permission to change content.
        let parsed = language
            .as_ref()
            .filter(|l| !l.scopes_ready())
            .map(|l| {
                let syntax = l
                    .assets
                    .syntaxes
                    .find_syntax_by_path(&l.syntax)
                    .ok_or("No syntax metadata for this document")?;
                vel_syntax::indent::scoped_spans(&l.assets.syntaxes, syntax, &self.text.to_string())
            })
            .transpose()?;
        let mut edits = Vec::new();
        for row in 0..self.text.len_lines() {
            let prefix: String = self
                .text
                .line(row)
                .chars()
                .take_while(|c| matches!(c, ' ' | '\t'))
                .collect();
            let width = vel_syntax::indent::indentation(&prefix, size);
            let replacement = if spaces {
                " ".repeat(width)
            } else {
                "\t".repeat(width / size) + &" ".repeat(width % size)
            };
            if prefix != replacement {
                let start = self.text.line_to_byte(row);
                // Leading whitespace in strings/heredocs is document content (notably
                // <<-EOF's tab stripping). Unknown scopes never authorize conversion.
                let protected = if let Some(spans) = &parsed {
                    let first = spans.partition_point(|span| span.range.end <= start);
                    let leading_spans = &spans[first..];
                    if !leading_spans
                        .first()
                        .is_some_and(|span| span.range.start <= start)
                        || !leading_spans
                            .iter()
                            .take_while(|span| span.range.start < start + prefix.len())
                            .any(|span| span.range.end >= start + prefix.len())
                    {
                        true
                    } else {
                        leading_spans
                            .iter()
                            .take_while(|span| span.range.start < start + prefix.len())
                            .any(|span| vel_syntax::indent::is_string_or_heredoc(&span.scopes))
                    }
                } else {
                    language
                        .as_ref()
                        .and_then(|l| l.scope_snapshot_at(start))
                        .is_none_or(|snapshot| {
                            snapshot
                                .lines
                                .get(row - snapshot.range.start)
                                .is_none_or(|line| {
                                    line.runs()
                                        .take_while(|run| (run.start as usize) < prefix.len())
                                        .any(|run| {
                                            snapshot.stacks.get(run.stack).is_none_or(
                                                vel_syntax::indent::is_string_or_heredoc,
                                            )
                                        })
                                })
                        })
                };
                if protected {
                    continue;
                }
                edits.push((start..start + prefix.len(), replacement));
            }
        }
        drop(language);
        self.apply_edits(edits, None, EditKind::Other);
        if args["set_translate_tabs"].as_bool().unwrap_or(false) {
            self.settings.set(
                vel_config::settings::Layer::View,
                "translate_tabs_to_spaces",
                json!(spaces),
            );
        }
        self.sync();
        Ok(())
    }
    fn start_reindent(&mut self) -> Result<(), String> {
        let language = self.language.borrow();
        let l = language
            .as_ref()
            .ok_or("No syntax metadata for this document")?;
        let metadata = l.assets.metadata.clone();
        let set = l.assets.syntaxes.clone();
        let syntax = l.syntax.clone();
        let text = self.text.clone();
        let version = self.buffer.change_id();
        let buffer = self.buffer.id();
        let options = vel_syntax::indent::IndentOptions {
            tab_size: self.preferences.tab_size,
            spaces: self.preferences.translate_tabs_to_spaces,
        };
        let regions: Vec<_> = self.buffer.view(self.id).sel().iter().collect();
        let (tx, rx) = mpsc::channel();
        std::thread::Builder::new()
            .name("velocity-reindent".into())
            .spawn(move || {
                let edits = (|| {
                    let source = text.to_string();
                    let reference = set.find_syntax_by_path(&syntax).expect("bound syntax");
                    let spans = vel_syntax::indent::scoped_spans(&set, reference, &source)?;
                    let result = vel_syntax::indent::reindent(&source, &spans, &metadata, options);
                    let all = regions.iter().all(|r| r.empty());
                    let mut offset = 0;
                    let mut edits = Vec::new();
                    for (old, new) in source
                        .split_inclusive('\n')
                        .zip(result.split_inclusive('\n'))
                    {
                        let row = text.byte_to_line(offset);
                        let selected = all
                            || regions.iter().any(|r| {
                                text.byte_to_line(r.begin()) <= row
                                    && row
                                        <= text.byte_to_line(
                                            r.end().saturating_sub(usize::from(!r.empty())),
                                        )
                            });
                        let a = old.len() - old.trim_start_matches([' ', '\t']).len();
                        let b = new.len() - new.trim_start_matches([' ', '\t']).len();
                        if selected && old[..a] != new[..b] {
                            edits.push((offset..offset + a, new[..b].to_owned()));
                        }
                        offset += old.len();
                    }
                    Ok(edits)
                })();
                let _ = tx.send((buffer, version, edits));
            })
            .map_err(|e| e.to_string())?;
        self.reindent_job = Some(rx);
        Ok(())
    }
    pub fn fold_command(&mut self, name: &str, args: &Value) -> Result<(), String> {
        if name == "unfold_all" || (name == "fold_by_level" && args["level"] == 0) {
            self.set_folded(Vec::new());
            return Ok(());
        }
        let selections: Vec<_> = self.buffer.view(self.id).sel().iter().collect();
        let mut current = self.folded();
        if name == "unfold" {
            // Remove only the visible parent; its nested children stay folded.
            let visible = vel_render::fold::outermost(current.iter().map(|r| r.to_range()));
            current.retain(|fold| {
                !visible.contains(&fold.to_range())
                    || !selections.iter().any(|r| {
                        let row = self.text.byte_to_line(r.b);
                        (fold.begin() <= r.end() && r.begin() <= fold.end())
                            || self.text.byte_to_line(fold.begin()) == row
                    })
            });
        } else {
            let language = self.language.borrow();
            let indentation = crate::annotations::fold_state::indentation_folds(self);
            let Some(candidates) = indentation.as_deref().or_else(|| {
                language
                    .as_ref()
                    .and_then(|l| l.analysis.as_ref())
                    .map(|a| a.folds.as_slice())
            }) else {
                // Folding uses syntax-aware regions, not a guessed block.
                // https://docs.sublimetext.io/reference/commands.html
                drop(language);
                if name == "fold" {
                    current.extend(selections.iter().filter(|r| !r.empty()).copied());
                }
                self.set_folded(current);
                self.actions.push((
                    "command_note".into(),
                    json!({"message":"Code folding is not ready yet."}),
                ));
                return Ok(());
            };
            let include_newline = self.settings.bool("fold_include_trailing_newline", false);
            let range = |f: &crate::language::Fold| {
                crate::annotations::fold_state::code_fold_range(&self.text, f, include_newline)
            };
            if name == "fold_by_level" || name == "fold_tag_attributes" {
                let level = args["level"].as_u64().unwrap_or(1) as usize;
                if name == "fold_by_level" {
                    current.clear();
                }
                current.extend(
                    candidates
                        .iter()
                        .filter(|f| {
                            if name == "fold_tag_attributes" {
                                f.attributes
                            } else {
                                !f.attributes && f.level == level
                            }
                        })
                        .filter_map(range)
                        .map(Region::from),
                );
            } else {
                for selection in selections {
                    if !selection.empty() {
                        current.push(selection);
                        continue;
                    }
                    if let Some(fold) = candidates
                        .iter()
                        .filter(|f| !f.attributes)
                        .filter_map(range)
                        .filter(|range| {
                            self.text.byte_to_line(range.start)
                                <= self.text.byte_to_line(selection.b)
                                && selection.b <= range.end
                                && !current.iter().any(|r| r.to_range() == *range)
                        })
                        .min_by_key(|range| range.len())
                    {
                        current.push(Region::from(fold));
                    }
                }
            }
        }
        self.set_folded(current);
        Ok(())
    }
    /// Installs a fold forest without discarding nested children.
    pub fn set_folded(&mut self, mut folds: Vec<Region>) {
        folds.retain(|r| !r.empty() && r.end() <= self.text.len_bytes());
        folds.sort_by_key(|r| (r.begin(), std::cmp::Reverse(r.end())));
        folds.dedup_by_key(|r| r.to_range());
        let old = self.buffer.view(self.id).sel();
        let primary = old.primary_index();
        let outer = vel_render::fold::outermost(folds.iter().map(|r| r.to_range()));
        let mut at = 0;
        let mut snap = |p| {
            while outer.get(at).is_some_and(|f| f.end <= p) {
                at += 1;
            }
            outer
                .get(at)
                .filter(|f| f.start < p && p < f.end)
                .map_or(p, |f| f.start)
        };
        let selection = selection_primary(
            old.iter()
                .map(|r| {
                    let a = snap(r.begin());
                    let b = snap(r.end());
                    Region {
                        a: if r.a <= r.b { a } else { b },
                        b: if r.a <= r.b { b } else { a },
                        ..r
                    }
                })
                .collect(),
            primary,
        );
        let moved = old != &selection;
        self.buffer.set_selection(self.id, selection);
        self.buffer.add_regions(self.id, FOLDS, folds, true);
        self.annotations.borrow_mut().reset_folds(self.id);
        self.layout.borrow_mut().invalidate();
        if moved {
            self.sync();
        }
    }
    /// Returns the live fold forest. Selection endpoints reveal every enclosing
    /// fold, including queries after Find/Goto/undo and before the next scene.
    pub fn folded(&self) -> Vec<Region> {
        self.annotations.borrow_mut().folded(&self.buffer, self.id)
    }

    pub(crate) fn line_command_folds(&self) -> Option<Vec<Region>> {
        self.buffer
            .view(self.id)
            .get_regions(FOLDS)
            .filter(|set| !set.is_empty())
            .map(|_| self.folded())
    }

    pub(crate) fn reveal_line_edits(
        &mut self,
        before: vel_buffer::ChangeId,
        mut folds: Vec<Region>,
    ) {
        if before == self.buffer.change_id() || folds.is_empty() {
            return;
        }
        // Join and duplicate aren't reorderings: reveal any hidden content they change.
        if let Some(maps) = self.buffer.changes_since(before) {
            for (_, map) in maps {
                folds.retain_mut(|f| {
                    let edits = map.changes();
                    let i = edits.partition_point(|c| c.old_range.end <= f.begin());
                    if edits.get(i).is_some_and(|c| c.old_range.start < f.end()) {
                        return false;
                    }
                    *f = map.transform_region(*f);
                    !f.empty()
                });
            }
        } else {
            folds.clear();
        }
        if self
            .buffer
            .view(self.id)
            .get_regions(FOLDS)
            .is_some_and(|set| set.regions != folds)
        {
            self.buffer.add_regions(self.id, FOLDS, folds, true);
            self.annotations.borrow_mut().reset_folds(self.id);
            self.layout.borrow_mut().invalidate();
        }
    }

    /// Captures the visible forest, including reveals since the last text edit.
    pub(crate) fn folded_view_state(
        &self,
        id: vel_buffer::ViewId,
        scroll: (f64, f64),
    ) -> vel_session::ViewState {
        let mut state = vel_session::ViewState::capture(&self.buffer, id, scroll);
        state.folds = self
            .annotations
            .borrow_mut()
            .folded(&self.buffer, id)
            .into_iter()
            .map(Into::into)
            .collect();
        state
    }

    /// Native undo history restores raw region sets. The saved live forest is
    /// authoritative for each sheet, including already imported clone views.
    pub(crate) fn restore_folded_view_state(
        &mut self,
        state: &vel_session::ViewState,
        id: vel_buffer::ViewId,
    ) {
        let text = self.buffer.text();
        let folds = state
            .folds
            .iter()
            .map(|p| {
                Region::new(
                    text.floor_char_boundary(p.a.min(text.len_bytes())),
                    text.floor_char_boundary(p.b.min(text.len_bytes())),
                )
            })
            .filter(|r| !r.empty())
            .collect();
        self.buffer.add_regions(id, FOLDS, folds, true);
        self.annotations.borrow_mut().reset_folds(id);
        self.layout.borrow_mut().invalidate();
    }

    /// Fold-aware horizontal motions run at the host's first text-command hook.
    pub(crate) fn fold_navigation_command(&mut self, name: &str, args: &Value) -> bool {
        if self
            .buffer
            .view(self.id)
            .get_regions(FOLDS)
            .is_none_or(|set| set.regions.is_empty())
        {
            return false;
        }
        let mut folds = self.folded();
        // Expose selected/deleted bytes, and insertion at a hidden fold end. Public
        // build 4143 notes (https://www.sublimetext.com/download) specify the fold
        // range, but not insertion at its end: reveal it so the caret and edit agree.
        if matches!(
            name,
            "insert"
                | "paste"
                | "paste_and_indent"
                | "insert_snippet"
                | "left_delete"
                | "right_delete"
                | "delete_left_right"
                | "delete_word"
                | "insert_best_completion"
                | "commit_completion"
        ) {
            let insertion = !matches!(
                name,
                "left_delete" | "right_delete" | "delete_left_right" | "delete_word"
            );
            let mut edits: Vec<_> = self
                .buffer
                .view(self.id)
                .sel()
                .iter()
                .map(|r| {
                    if !r.empty() {
                        r.to_range()
                    } else if name == "delete_left_right" {
                        self.text.prev_grapheme_boundary(r.b)..self.text.next_grapheme_boundary(r.b)
                    } else if name == "left_delete"
                        || (name == "delete_word" && args["forward"] != true)
                    {
                        self.text.prev_grapheme_boundary(r.b)..r.b
                    } else if name == "right_delete" || name == "delete_word" {
                        r.b..self.text.next_grapheme_boundary(r.b)
                    } else {
                        r.b..r.b
                    }
                })
                .collect();
            if !edits.is_sorted_by_key(|r| r.start) {
                edits.sort_unstable_by_key(|r| r.start);
            }
            let mut at = 0;
            folds.retain(|f| {
                while edits.get(at).is_some_and(|r| r.end <= f.begin()) {
                    at += 1;
                }
                !edits.get(at).is_some_and(|r| {
                    r.start < f.end()
                        || (insertion && r.is_empty() && r.start == f.end() && {
                            let row = self.text.byte_to_line(f.end());
                            let start = self.text.line_to_byte(row);
                            // Only an empty projected suffix is drawn on
                            // the header; a visible closing line starts at 0.
                            f.end() > start
                                && f.end() == start + crate::layout::body_len(&self.text, row)
                        })
                })
            });
        }
        if self
            .buffer
            .view(self.id)
            .get_regions(FOLDS)
            .is_some_and(|set| set.regions != folds)
        {
            self.buffer.add_regions(self.id, FOLDS, folds.clone(), true);
            self.annotations.borrow_mut().reset_folds(self.id);
            self.layout.borrow_mut().invalidate();
        }
        if folds.is_empty() {
            return false;
        }
        if name != "move" || args["by"].as_str().unwrap_or("characters") != "characters" {
            return false;
        }
        let forward = args["forward"].as_bool().unwrap_or(false);
        let extend = args["extend"].as_bool().unwrap_or(false);
        let old = self.buffer.view(self.id).sel();
        let primary = old.primary_index();
        let outer = vel_render::fold::outermost(folds.iter().map(|r| r.to_range()));
        let mut fold_at = 0;
        let regions = old
            .iter()
            .map(|r| {
                let mut at = if !extend && !r.empty() {
                    if forward { r.end() } else { r.begin() }
                } else {
                    let next = if forward {
                        self.text.next_grapheme_boundary(r.b)
                    } else {
                        self.text.prev_grapheme_boundary(r.b)
                    };
                    while outer.get(fold_at).is_some_and(|f| f.end < r.b) {
                        fold_at += 1;
                    }
                    outer
                        .get(fold_at)
                        .filter(|f| {
                            if forward {
                                f.start <= r.b && next < f.end
                            } else {
                                f.start < next && r.b <= f.end
                            }
                        })
                        .map_or(next, |f| if forward { f.end } else { f.start })
                };
                at = at.min(self.text.len_bytes());
                Region::new(if extend { r.a } else { at }, at)
            })
            .collect();
        self.set_selection(selection_primary(regions, primary));
        true
    }
}
pub(crate) fn selection_primary(mut regions: Vec<Region>, primary: usize) -> Selection {
    if primary < regions.len() {
        let r = regions.remove(primary);
        regions.push(r);
    }
    Selection::from_regions(regions)
}

/// The regions of the last copy or cut made in this process, kept while the clipboard still
/// holds the text it produced.
#[derive(Clone, Debug)]
pub struct LastCopy {
    text: String,
    /// Text of each copied region.
    pub parts: Vec<String>,
    /// The regions were whole lines copied from empty selections.
    pub whole_lines: bool,
}
thread_local! {
    static LAST_COPY: std::cell::RefCell<Option<LastCopy>> = const { std::cell::RefCell::new(None) };
}
/// Records a copy or cut that put `text` on the clipboard.
pub fn remember_copy(text: &str, parts: Vec<String>, whole_lines: bool) {
    LAST_COPY.with(|c| {
        *c.borrow_mut() = Some(LastCopy {
            text: normalize_line_breaks(text),
            parts,
            whole_lines,
        })
    });
}
/// The last copy, if the (normalized) clipboard still holds its text.
pub fn last_copy(clipboard: &str) -> Option<LastCopy> {
    LAST_COPY.with(|c| c.borrow().clone().filter(|c| c.text == clipboard))
}
pub fn forget_copy() {
    LAST_COPY.with(|c| c.borrow_mut().take());
}
/// Converts CRLF and lone CR line breaks to LF.
pub fn normalize_line_breaks(text: &str) -> String {
    if text.contains('\r') {
        text.replace("\r\n", "\n").replace('\r', "\n")
    } else {
        text.to_owned()
    }
}

/// Re-bases the indentation of pasted `text` onto `dest`: the whitespace prefix shared by its
/// non-blank lines is replaced by `dest`, and blank lines become empty. With `inline` the first
/// line continues the destination line at the caret, so it gets no prefix, and it only counts
/// towards the shared prefix when it starts with whitespace (it was copied from a line start).
pub fn reindent_block(text: &str, dest: &str, inline: bool) -> String {
    let lines: Vec<&str> = text.split('\n').collect();
    let first_counts = !inline || lines[0].starts_with([' ', '\t']);
    let mut base: Option<&str> = None;
    for (i, line) in lines.iter().enumerate() {
        if (i == 0 && !first_counts) || line.trim().is_empty() {
            continue;
        }
        let prefix = &line[..line.len() - line.trim_start_matches([' ', '\t']).len()];
        base = Some(match base {
            None => prefix,
            Some(b) => {
                let common = b
                    .bytes()
                    .zip(prefix.bytes())
                    .take_while(|(x, y)| x == y)
                    .count();
                &b[..common]
            }
        });
    }
    let base = base.unwrap_or("");
    let strip = |line: &str| -> String {
        line.strip_prefix(base)
            .unwrap_or_else(|| line.trim_start_matches([' ', '\t']))
            .to_owned()
    };
    lines
        .iter()
        .enumerate()
        .map(|(i, line)| {
            if inline && i == 0 {
                if first_counts {
                    strip(line)
                } else {
                    (*line).to_owned()
                }
            } else if line.trim().is_empty() {
                String::new()
            } else {
                format!("{dest}{}", strip(line))
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

